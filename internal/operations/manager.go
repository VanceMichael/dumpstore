// History bounds (see spec FR-14). Named constants so operators/reviewers
// have one place to adjust retention.
const (
	// DefaultMaxStepsPerOperation is the per-operation step ring size.
	DefaultMaxStepsPerOperation = 500
	// DefaultMaxStepMsgBytes caps a single step message (ansible stdout).
	DefaultMaxStepMsgBytes = 16 * 1024
	// DefaultRetainMax is the number of terminal operations kept in memory.
	DefaultRetainMax = 200
	// DefaultRetentionTTL is how long a terminal operation remains queryable.
	DefaultRetentionTTL = time.Hour
	// DefaultTombstoneMax bounds the ring of evicted IDs that still answer
	// 410 instead of 404.
	DefaultTombstoneMax = 256
	// journalBytesCap bounds the replay journal payload memory per operation
	// (500 steps × a few hundred bytes typical); oversized single steps are
	// still retained as the newest event, mirroring Journal semantics.
	journalBytesCap = 512 * 1024

	serverIDBytes = 12 // 24 hex chars, matching jobs.ID style
)

// Config holds the bounded-history parameters of a Manager.
type Config struct {
	MaxStepsPerOperation int
	MaxStepMsgBytes      int
	RetainMax            int
	RetentionTTL         time.Duration
	TombstoneMax         int
}

// DefaultConfig returns the production retention settings.
func DefaultConfig() Config {
	return Config{
		MaxStepsPerOperation: DefaultMaxStepsPerOperation,
		MaxStepMsgBytes:      DefaultMaxStepMsgBytes,
		RetainMax:            DefaultRetainMax,
		RetentionTTL:         DefaultRetentionTTL,
		TombstoneMax:         DefaultTombstoneMax,
	}
}

func (c Config) withDefaults() Config {
	d := DefaultConfig()
	if c.MaxStepsPerOperation <= 0 {
		c.MaxStepsPerOperation = d.MaxStepsPerOperation
	}
	if c.MaxStepMsgBytes <= 0 {
		c.MaxStepMsgBytes = d.MaxStepMsgBytes
	}
	if c.RetainMax <= 0 {
		c.RetainMax = d.RetainMax
	}
	if c.RetentionTTL <= 0 {
		c.RetentionTTL = d.RetentionTTL
	}
	if c.TombstoneMax <= 0 {
		c.TombstoneMax = d.TombstoneMax
	}
	return c
}

// StartOutcome tells an API caller whether Start created a new operation or
// resolved a replayed (idempotent) request.
type StartOutcome int

const (
	StartCreated StartOutcome = iota
	StartReplayRunning
	StartReplayTerminal
)

// tombstone records an evicted operation ID so callers get a definitive 410
// ("existed, now gone") rather than a 404 ("never seen").
type tombstone struct {
	id       string
	prunedAt time.Time
}

// Manager owns live, retained and tombstoned operations. Safe for concurrent
// use.
type Manager struct {
	cfg Config
	now func() time.Time

	mu         sync.Mutex
	ops        map[string]*Operation
	tombstones []tombstone

	accepts  int64
	finished map[Status]int64
}

// NewManager constructs a Manager with production bounds.
func NewManager(cfg Config) *Manager {
	return newManager(cfg, func() time.Time { return time.Now().UTC() })
}

func newManager(cfg Config, now func() time.Time) *Manager {
	return &Manager{
		cfg:      cfg.withDefaults(),
		now:      now,
		ops:      make(map[string]*Operation),
		finished: make(map[Status]int64),
	}
}

// clientIDRe accepts canonical op_<UUID> identifiers generated by browsers
// (X-Operation-ID). Strict canonical shape keeps the header free-form-proof.
var clientIDRe = regexp.MustCompile(`^op_[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$`)

// ValidClientID reports whether proposedID is a syntactically acceptable
// client-generated operation ID.
func ValidClientID(id string) bool { return clientIDRe.MatchString(id) }

func newServerID() (string, error) {
	var b [serverIDBytes]byte
	if _, err := rand.Read(b[:]); err != nil {
		return "", err
	}
	return hex.EncodeToString(b[:]), nil
}

// Start accepts a change into the registry.
//
// proposedID empty → a server-generated hex ID is assigned.
// proposedID set → it must match the canonical client shape; an existing ID
// returns the existing operation with StartReplayRunning/StartReplayTerminal
// and MUST NOT be executed again.
//
// Replaying an expired ID returns ErrExpired; a malformed ID returns
// ErrInvalidID.
func (m *Manager) Start(proposedID, action, target, reqID string) (*Operation, StartOutcome, error) {
	if proposedID != "" && !ValidClientID(proposedID) {
		return nil, 0, ErrInvalidID
	}

	m.mu.Lock()
	defer m.mu.Unlock()

	m.evictExpiredLocked()

	if proposedID != "" {
		if _, buried := m.tombstoneIndexLocked(proposedID); buried {
			return nil, 0, ErrExpired
		}
		if existing, ok := m.ops[proposedID]; ok {
			if existing.Snapshot().Status.Terminal() {
				return existing, StartReplayTerminal, nil
			}
			return existing, StartReplayRunning, nil
		}
	}

	id := proposedID
	if id == "" {
		var err error
		id, err = newServerID()
		if err != nil {
			return nil, 0, err
		}
	}

	now := m.now()
	op := &Operation{
		rec: Record{
			ID:        id,
			Action:    action,
			Target:    target,
			ReqID:     reqID,
			Status:    StatusRunning,
			Steps:     []Step{},
			StartedAt: now,
		},
		outcome: "",
		journal: broker.NewJournal(m.cfg.MaxStepsPerOperation, journalBytesCap),
		done:    make(chan struct{}),
		started: now,
	}
	m.ops[id] = op
	m.accepts++

	slog.Info("operation accepted",
		"op_id", id, "req_id", reqID, "action", action, "target", target)
	return op, StartCreated, nil
}

// Get returns the operation for id, or ErrExpired/ErrNotFound.
func (m *Manager) Get(id string) (*Operation, error) {
	m.mu.Lock()
	defer m.mu.Unlock()

	m.evictExpiredLocked()
	if _, buried := m.tombstoneIndexLocked(id); buried {
		return nil, ErrExpired
	}
	if op, ok := m.ops[id]; ok {
		return op, nil
	}
	if !validLookupID(id) {
		return nil, ErrInvalidID
	}
	return nil, ErrNotFound
}

// validLookupID accepts either client UUID IDs or server-generated 24-hex IDs.
func validLookupID(id string) bool {
	if ValidClientID(id) {
		return true
	}
	if len(id) != 2*serverIDBytes {
		return false
	}
	for _, c := range id {
		if !((c >= '0' && c <= '9') || (c >= 'a' && c <= 'f')) {
			return false
		}
	}
	return true
}

// complete is called by an operation's response finaliser: it freezes the
// terminal state, updates counters and runs retention pruning.
func (m *Manager) complete(op *Operation, httpStatus int) {
	now := m.now()
	if !op.finish(httpStatus, now) {
		return // already terminal
	}
	rec := op.Snapshot()

	m.mu.Lock()
	m.finished[rec.Status]++
	m.pruneLocked(now)
	m.mu.Unlock()
}

// pruneLocked evicts terminal operations beyond RetainMax (oldest first) and
// any terminal operation older than RetentionTTL. Running operations are
// never evicted. Evicted IDs enter the bounded tombstone ring.
func (m *Manager) pruneLocked(now time.Time) {
	type item struct {
		id string
		at time.Time
	}
	var terminals []item
	for id, op := range m.ops {
		rec := op.Snapshot()
		if rec.Status.Terminal() {
			terminals = append(terminals, item{id, rec.FinishedAt})
		}
	}
	// Fast path: within the count cap and nothing TTL-expired.
	overCount := len(terminals) > m.cfg.RetainMax
	if !overCount {
		stale := false
		for _, it := range terminals {
			if now.Sub(it.at) > m.cfg.RetentionTTL {
				stale = true
				break
			}
		}
		if !stale {
			return
		}
	}
	// Oldest terminal first.
	sort.Slice(terminals, func(i, j int) bool { return terminals[i].at.Before(terminals[j].at) })

	evict := len(terminals) - m.cfg.RetainMax // must evict at least this many by count
	for _, it := range terminals {
		byTTL := now.Sub(it.at) > m.cfg.RetentionTTL
		if byTTL || evict > 0 {
			delete(m.ops, it.id)
			m.pushTombstoneLocked(tombstone{id: it.id, prunedAt: now})
			evict--
		}
	}
}

// runningCountLocked counts non-terminal operations; caller holds m.mu.
func (m *Manager) runningCountLocked() int {
	n := 0
	for _, op := range m.ops {
		if op.Snapshot().Status == StatusRunning {
			n++
		}
	}
	return n
}

// evictExpiredLocked drops tombstones older than the TTL. Terminal operations
// past their TTL are pruned here too so lazy lookups cannot resurrect them.
func (m *Manager) evictExpiredLocked() {
	now := m.now()
	kept := m.tombstones[:0]
	for _, ts := range m.tombstones {
		if now.Sub(ts.prunedAt) <= m.cfg.RetentionTTL {
			kept = append(kept, ts)
		}
	}
	m.tombstones = kept
	m.pruneLocked(now)
}

func (m *Manager) pushTombstoneLocked(ts tombstone) {
	m.tombstones = append(m.tombstones, ts)
	if len(m.tombstones) > m.cfg.TombstoneMax {
		copy(m.tombstones, m.tombstones[1:])
		m.tombstones[len(m.tombstones)-1] = tombstone{}
		m.tombstones = m.tombstones[:len(m.tombstones)-1]
	}
}

func (m *Manager) tombstoneIndexLocked(id string) (int, bool) {
	for i, ts := range m.tombstones {
		if ts.id == id {
			return i, true
		}
	}
	return 0, false
}

// AddStep records a step on op applying the manager's ring/message bounds.
func (m *Manager) AddStep(op *Operation, ts ansible.TaskStep) Step {
	return op.AddStep(m.cfg.MaxStepsPerOperation, m.cfg.MaxStepMsgBytes, ts)
}

// Complete finalises op exactly once and runs bounded-history pruning.
func (m *Manager) Complete(op *Operation, httpStatus int) { m.complete(op, httpStatus) }

// MaxSteps returns the configured per-operation step ring size (used by
// Operation.AddStep via the API wiring).
func (m *Manager) MaxSteps() int { return m.cfg.MaxStepsPerOperation }

// MaxStepMsgBytes returns the configured per-step message byte cap.
func (m *Manager) MaxStepMsgBytes() int { return m.cfg.MaxStepMsgBytes }

// RunningCount returns the number of currently non-terminal operations
// (metrics gauge backing).
func (m *Manager) RunningCount() int {
	m.mu.Lock()
	defer m.mu.Unlock()
	return m.runningCountLocked()
}

// FinishedCount returns the cumulative number of finalised operations by
// terminal status.
func (m *Manager) FinishedCount() map[Status]int64 {
	m.mu.Lock()
	defer m.mu.Unlock()
	out := make(map[Status]int64, len(m.finished))
	for k, v := range m.finished {
		out[k] = v
	}
	return out
}

// AcceptedCount returns the cumulative number of accepted operations.
func (m *Manager) AcceptedCount() int64 {
	m.mu.Lock()
	defer m.mu.Unlock()
	return m.accepts
}
